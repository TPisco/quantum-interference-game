"""Download the Higgsfield artwork and embed it in web/art-data.js.

    pip install pillow
    python tools/embed_art.py            # download missing files, then embed
    python tools/embed_art.py --offline  # only embed files already in assets/generated/

Reads assets/higgsfield_manifest.json. Every item is saved to
assets/generated/<file>. Items with "use": "web" are resized, converted to WebP
and written into web/art-data.js as data URIs (Qollab serves JS modules
reliably, loose image files less so). Video stills and the "video_clips"
(Kling 3.0 MP4s for the demo video, saved to assets/video/) are only downloaded.

Size budget: Qollab accepts files under 2 MB; this script keeps art-data.js well
under that and fails loudly if it would not.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "assets" / "higgsfield_manifest.json"
OUT_DIR = ROOT / "assets" / "generated"
ART_JS = ROOT / "web" / "art-data.js"
LIMIT = 1_900_000  # bytes, under Qollab's 2 MB per-file limit

SIZES = {"hero": (1600, 914, 72), "level": (256, 256, 82)}


def download(url: str, dest: Path) -> None:
    print(f"  downloading {dest.name}")
    with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310 - manifest URLs only
        dest.write_bytes(resp.read())


def webp_data_uri(path: Path, size: tuple[int, int, int]) -> str:
    from PIL import Image

    w, h, quality = size
    img = Image.open(path).convert("RGB")
    # Cover-crop to the target aspect ratio, then resize.
    src_ratio, dst_ratio = img.width / img.height, w / h
    if src_ratio > dst_ratio:
        nw = int(img.height * dst_ratio)
        left = (img.width - nw) // 2
        img = img.crop((left, 0, left + nw, img.height))
    elif src_ratio < dst_ratio:
        nh = int(img.width / dst_ratio)
        top = (img.height - nh) // 2
        img = img.crop((0, top, img.width, top + nh))
    img = img.resize((w, h), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=quality, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--offline", action="store_true", help="do not download; use files on disk")
    args = ap.parse_args()

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    hero = None
    levels: dict[str, str] = {}
    for item in manifest["items"]:
        dest = OUT_DIR / item["file"]
        if not dest.exists():
            if args.offline:
                print(f"  missing {dest.name} (skipped)")
                continue
            try:
                download(item["url"], dest)
            except Exception as exc:  # noqa: BLE001
                print(f"  could not download {item['file']}: {exc}")
                continue
        if item["use"] != "web":
            continue
        if item["key"] == "hero":
            hero = webp_data_uri(dest, SIZES["hero"])
        else:
            levels[item["key"]] = webp_data_uri(dest, SIZES["level"])

    for clip in manifest.get("video_clips", []):
        dest = ROOT / "assets" / clip["file"]
        if dest.exists() or args.offline:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        try:
            download(clip["url"], dest)
        except Exception as exc:  # noqa: BLE001
            print(f"  could not download {clip['file']}: {exc}")

    body = ("// GENERATED by tools/embed_art.py from assets/generated/*. Do not edit by hand.\n"
            "// Empty entries fall back to the SVG emblems in web/art.js.\n"
            f"export const ART_DATA = {json.dumps({'hero': hero, 'levels': levels}, indent=1)};\n")
    if len(body.encode()) > LIMIT:
        print(f"art-data.js would be {len(body.encode())} bytes (> {LIMIT}); lower the sizes")
        return 1
    ART_JS.write_text(body, encoding="utf-8")
    print(f"wrote {ART_JS.relative_to(ROOT)}: hero={'yes' if hero else 'no'}, "
          f"levels={sorted(levels)}, {len(body.encode()) / 1024:.0f} KiB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
